#!/usr/bin/env python3
"""把資料組的 dataset-v2（dataset.json）的「即時 10 分鐘」轉成 Wokwi 用的 crew_data.h

用法：
    python3 tools/make_crew_data.py dataset-v2/dataset.json crew_data.h

只取 ID 裡有 ":L:" 的即時資料（每人 600 秒、每秒一筆）。
7 天歷史資料（":H:"）給後端直接匯入，不放進 ESP32。
"""
import json
import sys
from datetime import datetime

CREW_ORDER = ["mira", "kai", "lin", "noa", "sol"]   # 要跟 sketch.ino 的 crew[] 順序一樣
SECONDS = 600
TEMP_BP_EVERY = 60

# 讀值品質的代碼（要跟 sketch.ino 的 enum SampleQuality 一樣）
QUALITY_CODES = {
    ("good", None): 0,
    ("poor", "motion_artifact"): 1,
    ("missing", "no_sample"): 2,
}


def quality_code(metric):
    q = metric["quality"]
    key = (q, None) if q == "good" else (q, metric.get("qualityReason"))
    if key not in QUALITY_CODES:
        sys.exit(f"不認得的品質：{key}（要先加到 QUALITY_CODES 和 sketch.ino）")
    return QUALITY_CODES[key]


def main(src, dst):
    data = json.load(open(src, encoding="utf-8"))
    live = [m for m in data["measurements"] if ":L:" in m["id"]]
    start = min(datetime.fromisoformat(m["observedAt"].replace("Z", "+00:00")) for m in live)

    rows = {c: [None] * SECONDS for c in CREW_ORDER}
    temp_bp = {c: [None] * (SECONDS // TEMP_BP_EVERY) for c in CREW_ORDER}

    for m in live:
        crew = m["crewId"]
        sec = int((datetime.fromisoformat(m["observedAt"].replace("Z", "+00:00")) - start).total_seconds())
        if crew not in rows or not 0 <= sec < SECONDS:
            sys.exit(f"資料超出範圍：{m['id']}")
        metrics = {x["code"]: x for x in m["metrics"]}

        hr, spo2, rr = metrics["heart_rate"], metrics["spo2"], metrics["respiratory_rate"]
        if rr["quality"] != "good":
            sys.exit(f"呼吸頻率有不是 good 的資料：{m['id']}（程式還沒處理）")
        hr_q, spo2_q = quality_code(hr), quality_code(spo2)
        exercise = 1 if hr["context"].get("activity") == "exercise" else 0
        flags = hr_q | (spo2_q << 2) | (exercise << 4)
        rows[crew][sec] = (
            int(hr["value"]) if hr["value"] is not None else 0,
            round(spo2["value"] * 10) if spo2["value"] is not None else 0,
            int(rr["value"]),
            flags,
        )

        if "temperature" in metrics:
            if sec % TEMP_BP_EVERY != 0:
                sys.exit(f"體溫不在整分鐘：{m['id']}")
            temp_bp[crew][sec // TEMP_BP_EVERY] = (
                round(metrics["temperature"]["value"] * 10),
                int(metrics["blood_pressure_systolic"]["value"]),
                int(metrics["blood_pressure_diastolic"]["value"]),
            )

    for c in CREW_ORDER:
        if None in rows[c] or None in temp_bp[c]:
            sys.exit(f"{c} 的資料有缺秒")

    out = []
    out.append("// crew_data.h")
    out.append(f"// {data.get('datasetId')} live 10 min, generated by tools/make_crew_data.py")
    out.append("#pragma once")
    out.append("#include <stdint.h>")
    out.append("")
    out.append(f"const int PLAYBACK_SECONDS = {SECONDS};")
    out.append(f"const int TEMP_BP_EVERY_SEC = {TEMP_BP_EVERY};")
    out.append("")
    out.append("// flags: bit 0-1 HR quality, bit 2-3 SpO2 quality (0 good, 1 poor, 2 missing), bit 4 exercise")
    out.append("struct PlaybackRow {")
    out.append("  uint8_t  hr;")
    out.append("  uint16_t spo2x10;   // 983 = 98.3 %")
    out.append("  uint8_t  rr;")
    out.append("  uint8_t  flags;")
    out.append("};")
    out.append("")
    out.append("struct TempBpRow {")
    out.append("  int16_t tempx10;    // 367 = 36.7 Cel")
    out.append("  int16_t sbp;")
    out.append("  int16_t dbp;")
    out.append("};")
    out.append("")
    for c in CREW_ORDER:
        name = c.upper()
        out.append(f"const PlaybackRow PLAYBACK_{name}[PLAYBACK_SECONDS] = {{")
        r = rows[c]
        for i in range(0, SECONDS, 10):
            chunk = ", ".join(f"{{{a},{b},{rr},{f}}}" for a, b, rr, f in r[i:i + 10])
            out.append(f"  {chunk},  // {i // 60:02d}:{i % 60:02d}")
        out.append("};")
        tb = ", ".join(f"{{{t},{s},{d}}}" for t, s, d in temp_bp[c])
        out.append(f"const TempBpRow TEMPBP_{name}[PLAYBACK_SECONDS / TEMP_BP_EVERY_SEC] = {{ {tb} }};")
        out.append("")
    out.append("// Mira, Kai, Lin, Noa, Sol")
    out.append("const PlaybackRow* const PLAYBACK[5] = { " + ", ".join(f"PLAYBACK_{c.upper()}" for c in CREW_ORDER) + " };")
    out.append("const TempBpRow*   const TEMPBP[5]   = { " + ", ".join(f"TEMPBP_{c.upper()}" for c in CREW_ORDER) + " };")
    out.append("")
    open(dst, "w", encoding="utf-8").write("\n".join(out))
    print(f"寫好 {dst}：{len(CREW_ORDER)} 人 × {SECONDS} 秒")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
